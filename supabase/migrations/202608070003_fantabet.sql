-- FantaBet core: versioned V1 rounds, deadline enforcement and derived scores.
-- Apply only after 202608070001_account_profiles.sql and 202608050001_partite.sql.
begin;

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table public.fantabet_rounds (
  id bigint generated by default as identity primary key,
  stagione_id smallint not null references public.stagioni(id),
  numero_giornata smallint not null,
  opens_at timestamptz not null,
  deadline_at timestamptz not null,
  status text not null default 'bozza',
  round_type text not null default 'STANDARD',
  rules_version smallint not null default 1,
  required_predictions smallint not null default 5,
  perfect_multiplier smallint not null default 2,
  consistency_block_size smallint not null default 5,
  consistency_bonus_points smallint not null default 10,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint fantabet_rounds_numero_giornata_positivo check (numero_giornata > 0),
  constraint fantabet_rounds_intervallo_valido check (opens_at < deadline_at),
  constraint fantabet_rounds_status_ammesso check (status in ('bozza', 'pubblicata', 'chiusa', 'valutata', 'annullata')),
  constraint fantabet_rounds_tipo_non_vuoto check (btrim(round_type) <> ''),
  constraint fantabet_rounds_versione_regole_positiva check (rules_version > 0),
  constraint fantabet_rounds_pronostici_richiesti_positivi check (required_predictions > 0),
  constraint fantabet_rounds_moltiplicatore_valido check (perfect_multiplier >= 1),
  constraint fantabet_rounds_blocco_costanza_positivo check (consistency_block_size > 0),
  constraint fantabet_rounds_bonus_costanza_non_negativo check (consistency_bonus_points >= 0),
  constraint fantabet_rounds_stagione_giornata_unique unique (stagione_id, numero_giornata)
);

create table public.fantabet_bets (
  id bigint generated by default as identity primary key,
  round_id bigint not null references public.fantabet_rounds(id) on delete cascade,
  partita_id bigint not null references public.partite(id),
  bet_type text not null,
  points_value smallint not null,
  display_order smallint not null,
  created_at timestamptz not null default now(),
  constraint fantabet_bets_type_non_vuoto check (btrim(bet_type) <> ''),
  constraint fantabet_bets_punti_positivi check (points_value > 0),
  constraint fantabet_bets_ordine_positivo check (display_order > 0),
  constraint fantabet_bets_round_partita_unique unique (round_id, partita_id),
  constraint fantabet_bets_round_ordine_unique unique (round_id, display_order)
);

create table public.fantabet_predictions (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  bet_id bigint not null references public.fantabet_bets(id) on delete cascade,
  scelta text not null,
  exact_home smallint null,
  exact_away smallint null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint fantabet_predictions_scelta_ammessa check (scelta in ('1', 'X', '2', 'UNDER', 'OVER', 'ESATTO')),
  constraint fantabet_predictions_exact_home_non_negativo check (exact_home is null or exact_home >= 0),
  constraint fantabet_predictions_exact_away_non_negativo check (exact_away is null or exact_away >= 0),
  constraint fantabet_predictions_profile_bet_unique unique (profile_id, bet_id)
);

create index fantabet_bets_round_idx on public.fantabet_bets (round_id);
create index fantabet_bets_partita_idx on public.fantabet_bets (partita_id);
create index fantabet_predictions_profile_idx on public.fantabet_predictions (profile_id);
create index fantabet_predictions_bet_idx on public.fantabet_predictions (bet_id);

