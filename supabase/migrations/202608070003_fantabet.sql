create policy fantabet_rounds_public_read
on public.fantabet_rounds for select
to anon, authenticated
using (status in ('pubblicata', 'chiusa', 'valutata'));

create policy fantabet_bets_public_read
on public.fantabet_bets for select
to anon, authenticated
using (exists (
  select 1 from public.fantabet_rounds round
  where round.id = round_id and round.status in ('pubblicata', 'chiusa', 'valutata')
));

create policy fantabet_predictions_read_own
on public.fantabet_predictions for select
to authenticated
using ((select auth.uid()) is not null and (select auth.uid()) = profile_id);

create policy fantabet_predictions_insert_own_before_deadline
on public.fantabet_predictions for insert
to authenticated
with check (
  (select auth.uid()) is not null
  and (select auth.uid()) = profile_id
  and public.fantabet_prediction_window_open(bet_id)
);

create policy fantabet_predictions_update_own_before_deadline
on public.fantabet_predictions for update
to authenticated
using (
  (select auth.uid()) is not null
  and (select auth.uid()) = profile_id
  and public.fantabet_prediction_window_open(bet_id)
)
with check (
  (select auth.uid()) is not null
  and (select auth.uid()) = profile_id
  and public.fantabet_prediction_window_open(bet_id)
);

